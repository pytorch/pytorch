from __future__ import annotations

import argparse
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
import re
import sys
from typing import TYPE_CHECKING


REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from tools.autograd.gen_python_functions import (
    load_signatures,
    should_generate_py_binding,
)
from tools.pyi.gen_pyi import generate_type_hints, get_py_torch_functions
from torchgen.gen import parse_native_yaml

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence


DEFAULT_NATIVE_YAML = REPO_ROOT / "aten/src/ATen/native/native_functions.yaml"
DEFAULT_TAGS_YAML = REPO_ROOT / "aten/src/ATen/native/tags.yaml"
DEFAULT_DEPRECATED_YAML = REPO_ROOT / "tools/autograd/deprecated.yaml"
DEFAULT_OUTPUT = REPO_ROOT / "test/typing/reveal/native_functions.py"

_RETURN_RE = re.compile(
    r"\)\s*->\s*(?P<return_type>.*?)\s*:(?:\s*#.*)?\s*\.\.\.", re.DOTALL
)


@dataclass(frozen=True)
class NativeFunctionTypeTestCase:
    op_name: str
    expression: str


# Keep this list small and representative. The return types are derived from
# native_functions.yaml through the same torchgen path used by tools/pyi/gen_pyi.py.
TEST_CASES: tuple[NativeFunctionTypeTestCase, ...] = (
    NativeFunctionTypeTestCase("relu", "torch.relu(x)"),
    NativeFunctionTypeTestCase("abs", "torch.abs(x)"),
    NativeFunctionTypeTestCase("clamp", "torch.clamp(x, min=0.0, max=1.0)"),
    NativeFunctionTypeTestCase("matmul", "torch.matmul(matrix, matrix_t)"),
    NativeFunctionTypeTestCase(
        "index_select", "torch.index_select(matrix, 0, indices)"
    ),
    NativeFunctionTypeTestCase("flatten", "torch.flatten(cube, start_dim=1)"),
    NativeFunctionTypeTestCase("reshape", "torch.reshape(x, (3, 2))"),
    NativeFunctionTypeTestCase("permute", "torch.permute(cube, (2, 0, 1))"),
    NativeFunctionTypeTestCase("transpose", "torch.transpose(matrix, 0, 1)"),
    NativeFunctionTypeTestCase(
        "sum", "torch.sum(matrix, dim=1, keepdim=True, dtype=torch.float64)"
    ),
    NativeFunctionTypeTestCase("amax", "torch.amax(cube, dim=(1, 2), keepdim=True)"),
    NativeFunctionTypeTestCase(
        "empty",
        "torch.empty((2, 3), dtype=torch.float32, device=None)",
    ),
    NativeFunctionTypeTestCase("zeros", "torch.zeros(2, 3, out=torch.empty(2, 3))"),
)

RETURN_TYPE_TO_REVEAL = {
    "Tensor": "{Tensor}",
}

NATIVE_FUNCTIONS_HEADER = """\
# mypy: disable-error-code="possibly-undefined"
# flake8: noqa
# This file is generated by tools/typing/gen_native_function_type_tests.py.
# Do not edit manually; update TEST_CASES in that generator.
import torch


x = torch.randn(2, 3)
matrix = torch.randn(2, 3)
matrix_t = torch.randn(3, 2)
cube = torch.randn(2, 3, 4)
indices = torch.tensor([0, 1], dtype=torch.long)

"""


def _extract_return_type(type_hint: str) -> str:
    match = _RETURN_RE.search(type_hint)
    if match is None:
        raise AssertionError(
            f"could not parse return type from generated hint: {type_hint}"
        )
    return " ".join(match.group("return_type").split())


def get_native_function_return_types(
    *,
    native_yaml_path: Path = DEFAULT_NATIVE_YAML,
    tags_yaml_path: Path = DEFAULT_TAGS_YAML,
    deprecated_yaml_path: Path = DEFAULT_DEPRECATED_YAML,
) -> Mapping[str, set[str]]:
    native_functions = parse_native_yaml(
        str(native_yaml_path), str(tags_yaml_path)
    ).native_functions
    native_functions = list(filter(should_generate_py_binding, native_functions))
    function_signatures = load_signatures(
        native_functions, str(deprecated_yaml_path), method=False, pyi=True
    )

    return_types: defaultdict[str, set[str]] = defaultdict(set)
    for group in get_py_torch_functions(function_signatures):
        for type_hint in generate_type_hints(group):
            return_types[group.signature.name].add(_extract_return_type(type_hint))
    return return_types


def _expected_reveal_for_case(
    case: NativeFunctionTypeTestCase, return_types: Mapping[str, set[str]]
) -> str:
    op_return_types = return_types.get(case.op_name)
    if op_return_types is None:
        raise AssertionError(
            f"{case.op_name} is not generated from native_functions.yaml"
        )
    if len(op_return_types) != 1:
        raise AssertionError(
            f"{case.op_name} has multiple generated return types: "
            f"{sorted(op_return_types)}"
        )

    return_type = next(iter(op_return_types))
    if return_type not in RETURN_TYPE_TO_REVEAL:
        raise AssertionError(
            f"{case.op_name} generated unsupported return type {return_type!r}; "
            "extend RETURN_TYPE_TO_REVEAL before adding this case"
        )
    return RETURN_TYPE_TO_REVEAL[return_type]


def render_native_function_type_tests(
    *,
    native_yaml_path: Path = DEFAULT_NATIVE_YAML,
    tags_yaml_path: Path = DEFAULT_TAGS_YAML,
    deprecated_yaml_path: Path = DEFAULT_DEPRECATED_YAML,
    test_cases: Sequence[NativeFunctionTypeTestCase] = TEST_CASES,
) -> str:
    return_types = get_native_function_return_types(
        native_yaml_path=native_yaml_path,
        tags_yaml_path=tags_yaml_path,
        deprecated_yaml_path=deprecated_yaml_path,
    )

    lines = NATIVE_FUNCTIONS_HEADER.splitlines()
    for case in test_cases:
        expected_reveal = _expected_reveal_for_case(case, return_types)
        lines.append(f"reveal_type({case.expression})  # E: {expected_reveal}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate mypy reveal tests for native_function type hints."
    )
    parser.add_argument("--native-yaml-path", type=Path, default=DEFAULT_NATIVE_YAML)
    parser.add_argument("--tags-yaml-path", type=Path, default=DEFAULT_TAGS_YAML)
    parser.add_argument(
        "--deprecated-yaml-path", type=Path, default=DEFAULT_DEPRECATED_YAML
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    rendered = render_native_function_type_tests(
        native_yaml_path=args.native_yaml_path,
        tags_yaml_path=args.tags_yaml_path,
        deprecated_yaml_path=args.deprecated_yaml_path,
    )
    args.output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
