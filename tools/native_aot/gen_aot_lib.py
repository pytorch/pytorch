"""Generate the native-AOT kernel library source from declarations + sidecars.

Each op's aot.py (contract: tools/native_aot/decl.py) states the C++
side as string-returning functions: cpp_dispatch_prelude() (optional
shared checks + setup), cpp_dispatch(spec) (one boolean per precompile
point), cpp_launch(spec, launch_fn) (the invocation), cpp_helpers()
(optional family-shared C++). The Python-side coverage check
(covered_axes, consumed by torch._native.aot_manifest) lives in the
same module -- the two sides are kept in sync by hand.

For each op with exported artifacts under ``<artifacts-dir>/<op>/``,
emits ``aot_<op>_<key>.cpp`` containing:

  * a launch_<prefix>() marshalling helper per exported kernel,
    emitted by the sidecar kind's Toolchain (see toolchains.py); every
    toolchain produces the same launcher signature, so cpp_launch and
    the guard chain are toolchain-blind
  * the stub kernel: helpers | prelude, then the dispatch chain -- one
    `if (cpp_dispatch(spec)) { cpp_launch; return true; }` branch per
    exported precompile point, then `return false` (the fallback)
  * registration on the generated at::native DispatchStub
    (<op>_aot_stub) via set_<device>_dispatch_ptr at static-init time

The kernel signature is the op's structured impl signature: outputs are
allocated by the wrapper's meta() before the stub runs, so bodies write
into them and return true, or return false to fall through to op.impl.

Requires torchgen (impl signature) but not a built torch.

Usage:
    python tools/native_aot/gen_aot_lib.py [--artifacts-dir build/native_aot]
"""

import argparse
import json
import os
import sys


REPO = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
)
sys.path.insert(0, REPO)

from torchgen import native_aot_decl as decl


OPS_DIR = os.path.join(REPO, "torch", "_native", "ops")

FILE_TMPL = """\
// @generated by tools/native_aot/gen_aot_lib.py from
// {decl_path} -- do not edit
//
// {precompute_note}
// core/Tensor.h, not ATen/ATen.h: the latter pulls Functions.h +
// NativeFunctions.h, i.e. ~1300 ATen/ops/*.h each, so every generated file
// depended on unrelated ops (conv2d, lstm, fft) and any schema edit rebuilt
// all of them -- exactly what AT_PER_OPERATOR_HEADERS exists to avoid.
// Declaration bodies that call an at:: FACTORY need its op header added
// here (empty is pre-added for the reduction family's accumulator).
#include <ATen/core/Tensor.h>
#include <ATen/NativeAotStubs.h>
#include <ATen/TensorIterator.h>
#include <ATen/cuda/CUDAContext.h>
#include <ATen/ops/empty.h>
#include <c10/cuda/CUDAStream.h>
#include <torch/library.h>

#include <algorithm>
#include <limits>

{kernel_includes}

namespace {{

// The DSL's exported ABI carries int32_t shape slots while aten sizes are
// int64_t; the generated gates decline rather than truncate. See
// _int32_size_gate in tools/native_aot/gen_aot_lib.py.
inline bool _naot_dim_too_big(int64_t d) {{
  return d > std::numeric_limits<int32_t>::max();
}}

{launchers}
bool {op}_{key_lc}_aot_kernel({params}) {{
{cond}
{guards}
  return false;
}}
{covers_fn}
}} // namespace

// Register on the generated DispatchStub (same mechanism as aten's own
// runtime-registered CUDA kernels; see ATen/native/DispatchStub.h).
namespace at::native {{
REGISTER_{key_uc}_DISPATCH({op}_aot_stub, &::{op}_{key_lc}_aot_kernel)
}} // namespace at::native
{covers_reg}"""

# Fast coverage predicate: the declaration's cpp_covers() body over the
# op's FUNCTIONAL schema arguments (plus a trailing optional `out` so
# the .out variant's kwarg binds). Registered as a catch-all custom op;
# torch._native.aot_manifest prefers it over the Python covered_axes
# matching when the library is loaded.
COVERS_FN_TMPL = """
bool {op}_{key_lc}_covers({params}) {{
{body}
}}
"""

COVERS_REG_TMPL = """
TORCH_LIBRARY_FRAGMENT(_native_aot, m) {{
  m.def("{schema}", &::{op}_{key_lc}_covers);
}}
"""


from tools.native_aot import toolchains


def indent(code: str, pad: str) -> str:
    return "\n".join(pad + l if l.strip() else l for l in code.rstrip().splitlines())


def gen_launcher(sidecar: dict) -> str:
    return toolchains.get_toolchain(sidecar.get("kind", "cutedsl")).gen_launcher(
        sidecar
    )


def _arch_gate(d, sidecars: list[dict]) -> str:
    """Runtime device gate: decline (fall through to the JIT/aten
    routes) on any device outside the intersection of the arches the
    DECLARATION supports (d.ARCHS -- op intent) and the arches the
    artifacts were actually COMPILED for (sidecar 'arch' -- build
    fact). Without it, a wheel whose artifacts target Blackwell would
    attempt a wrong-arch cubin load on Hopper and fail at launch
    instead of falling back. Emitted ahead of the declaration's own
    prelude AND into cpp_covers, so declarations never hand-write arch
    checks. Sidecars with no recorded arch (exported on-device) gate on
    d.ARCHS alone -- the artifact matches the builder by construction.
    Shipped arches outside d.ARCHS are a packaging bug: error here
    rather than gate on kernels the op disowns."""
    shipped = {a for sc in sidecars if isinstance(a := sc.get("arch"), str)}
    if shipped - set(d.ARCHS):
        raise RuntimeError(
            f"{d.ATEN_OP}: artifacts exported for {sorted(shipped)} "
            f"but the declaration supports only {d.ARCHS}; re-export "
            f"(export.py skips unsupported arches)"
        )
    gate = sorted(shipped) or sorted(d.ARCHS)
    majors = sorted({int(a.removeprefix("sm_").rstrip("a")) // 10 for a in gate})
    accept = " || ".join(
        f"at::cuda::getCurrentDeviceProperties()->major == {m}" for m in majors
    )
    return (
        f"  // Device gate: declaration ARCHS x shipped artifacts = {' '.join(gate)}\n"
        f"  if (!({accept})) return false;\n"
    )


def _int32_size_gate(params: str) -> str:
    """Runtime gate: decline any call whose tensor has a dimension that
    does not fit in int32.

    aten stores sizes and strides as int64_t (TensorBase.h: `int64_t
    size(int64_t)`), but CuTeDSL's export_to_c emits `int32_t
    dynamic_shapes[]` in the generated per-kernel ABI header, and it
    does so REGARDLESS of the symbol width the builder asked for --
    verified by probe: declaring the shape with cute.sym_int64()
    produces a byte-identical header to cute.sym_int() (strides DO honor
    sym_int64, sizes do not). So the 2^31 ceiling is imposed by the DSL's
    C ABI, not by our kernels, and we cannot widen it from this side.

    Without this gate the launcher's `static_cast<int32_t>(t.size(dim))`
    would silently truncate a >=2^31 dim and hand the kernel a wrong
    (possibly negative) extent: wrong results or corrupted memory, with
    no error. Declining instead routes the call to the JIT layer or to
    stock aten, neither of which has the limit.

    Emitted ahead of the declaration's prelude AND into cpp_covers (like
    _arch_gate) so no declaration has to hand-write it, and so coverage
    never claims a shape the stub will refuse.

    TODO(native-aot): drop this once CuTeDSL emits int64_t shape slots
    (or honors the requested symbol width) in export_to_c; then sizes
    match aten and the gate becomes dead code.
    """
    # Parameter list -> the at::Tensor names in scope. The prelude sees
    # plain `const at::Tensor & x`; cpp_covers sees the functional schema
    # plus out-variant outputs as `const std::optional<at::Tensor>& x`.
    plain: list[str] = []
    optional: list[str] = []
    for raw in params.split(","):
        p = raw.strip()
        if not p:
            continue
        name = p.split()[-1].lstrip("&*")
        if "std::optional<at::Tensor>" in p:
            optional.append(name)
        elif "at::Tensor" in p:
            plain.append(name)
    if not plain and not optional:
        return ""
    checks = [
        f"{n}.sizes().end() != std::find_if({n}.sizes().begin(), {n}.sizes().end(), _naot_dim_too_big)"
        for n in plain
    ]
    checks += [
        f"({n}.has_value() && {n}->sizes().end() != "
        f"std::find_if({n}->sizes().begin(), {n}->sizes().end(), _naot_dim_too_big))"
        for n in optional
    ]
    return (
        "  // Size gate: the DSL's exported ABI carries int32_t shape slots\n"
        "  // (see _int32_size_gate); a bigger dim would truncate silently.\n"
        f"  if (C10_UNLIKELY({' || '.join(checks)})) return false;\n"
    )


def gen_op(
    op: str,
    key: str,
    d,
    sidecars: list[dict],
    impl_params: str,
    covers: tuple[str, str, str] | None = None,
    precomputed: list[str] | None = None,
    decl_path: str = "",
) -> str:
    branches = []
    for s in sidecars:
        dispatch = d.cpp_dispatch(s["spec"]).strip()
        launch = d.cpp_launch(s["spec"], f"launch_{s['prefix']}")
        branches.append(
            f"  if ({dispatch}) {{\n{indent(launch, '    ')}\n    return true;\n  }}"
        )
    prelude_fn = getattr(d, "cpp_dispatch_prelude", None)
    helpers_fn = getattr(d, "cpp_helpers", None)
    prelude = (prelude_fn() or "") if prelude_fn else ""
    helpers = (helpers_fn() or "") if helpers_fn else ""
    covers_fn = covers_reg = ""
    if covers is not None:
        covers_params, covers_schema, covers_body = covers
        # Coverage must be no wider than the stub's acceptance: the
        # arch gate declines in the stub, so covers must decline on the
        # same devices or gated calls lose their JIT route.
        covers_fn = COVERS_FN_TMPL.format(
            op=op,
            key_lc=key.lower(),
            params=covers_params,
            body=_arch_gate(d, sidecars)
            + _int32_size_gate(covers_params)
            + indent(covers_body, "  "),
        )
        covers_reg = COVERS_REG_TMPL.format(
            op=op, key_lc=key.lower(), schema=covers_schema
        )
    # State the group's precompute behavior where authors debug: a raw
    # dim compared unwrapped against self.dim()-1 silently declines
    # every negative-dim call (PAIN_POINTS P14).
    if precomputed:
        note = (
            f"Structured META precomputes (impl receives them wrapped/"
            f"replaced): {', '.join(precomputed)}"
        )
    else:
        note = (
            "Structured META precomputes NOTHING for this op: schema "
            "args (incl. any dim) arrive RAW -- wrap dims before comparing."
        )
    return FILE_TMPL.format(
        op=op,
        key_lc=key.lower(),
        key_uc=key.upper(),
        decl_path=decl_path or f"the declaration for aten::{op}",
        precompute_note=note,
        covers_fn=covers_fn,
        covers_reg=covers_reg,
        kernel_includes="\n".join(
            dict.fromkeys(  # ordered dedup across sidecars
                line
                for sc in sidecars
                for tc in [toolchains.get_toolchain(sc.get("kind", "cutedsl"))]
                for line in (*tc.kernel_includes(sc), *tc.launcher_includes)
            )
        ),
        launchers="\n".join(
            ([helpers] if helpers else []) + [gen_launcher(s) for s in sidecars]
        ),
        params=impl_params,
        cond=_arch_gate(d, sidecars)
        + _int32_size_gate(impl_params)
        + indent(prelude, "  "),
        guards="\n".join(branches),
    )


def _structured_group(op: str):
    from torchgen.gen import get_grouped_native_functions, parse_native_yaml
    from torchgen.model import NativeFunctionsGroup

    aten = os.path.join(REPO, "aten", "src", "ATen")
    parsed = parse_native_yaml(
        os.path.join(aten, "native", "native_functions.yaml"),
        os.path.join(aten, "native", "tags.yaml"),
    )
    for g in get_grouped_native_functions(parsed.native_functions):
        # Base names repeat across groups (e.g. bmm vs bmm.dtype); the
        # kernel signature must come from the STRUCTURED group. Qualified
        # ops ("gt.Tensor") match the exact functional overload name.
        if isinstance(g, NativeFunctionsGroup) and g.structured:
            name = (
                str(g.functional.func.name)
                if "." in op
                else g.functional.func.name.name.base
            )
            if name == op:
                return g
    raise RuntimeError(f"no structured group for {op}")


def impl_signature_params(op: str) -> str:
    from torchgen.api import structured
    from torchgen.context import native_function_manager

    g = _structured_group(op)
    with native_function_manager(g):
        return ", ".join(b.decl() for b in structured.impl_arguments(g))


def precomputed_args(op: str) -> list[str]:
    """Schema argument names the structured META precomputes (replaces)
    before the impl runs -- e.g. index_add's dim arrives already
    maybe_wrap_dim'ed, while sum.dim_IntList's dim arrives RAW.
    Declarations must know which they get (PAIN_POINTS P14): a prelude
    comparing a raw negative dim against self.dim()-1 silently declines
    every dim=-1 call to stock aten. The generated .cpp states this per
    op; this helper answers it programmatically."""
    g = _structured_group(op)
    pre = g.out.precomputed
    return sorted(pre.replace.keys()) if pre is not None else []


def covers_signature(op: str) -> tuple[str, str]:
    """(C++ params, torch.library schema) for the fast coverage
    predicate: the FUNCTIONAL schema arguments (SymInt degraded to int
    -- symbolic sizes can't be covered anyway; a failed bind falls back
    to the Python path) plus the out variant's outputs as trailing
    optionals so calls arriving through the .out overload bind too.
    """
    from torchgen.api.types import DispatcherSignature
    from torchgen.context import native_function_manager

    g = _structured_group(op)
    with native_function_manager(g):
        sig = DispatcherSignature.from_schema(g.functional.func, symint=False)
        params = [a.decl() for a in sig.arguments()]
    # Render per-argument from the model (not string surgery on the
    # whole schema): SymInt -> int argument-by-argument, and the
    # kwarg-only marker reconstructed from the model's split.
    args = g.functional.func.arguments
    pos = [str(a).replace("SymInt", "int") for a in args.flat_positional]
    kw = [str(a).replace("SymInt", "int") for a in args.flat_kwarg_only]
    pieces = pos + (["*", *kw] if kw else [])
    # Trailing out-variant outputs bind the .out overload's kwargs;
    # appended last, so kwarg-only exactly when the schema already has
    # a kwarg section (matching the C++ params' positional binding).
    for a in g.out.func.arguments.out:
        params.append(f"const std::optional<at::Tensor>& {a.name}")
        pieces.append(f"Tensor? {a.name}=None")
    schema_args = ", ".join(pieces)
    # Op name in the registered schema is the decl_id (dots are illegal
    # in custom-op names); the runtime resolves covers_<decl_id> too.
    return (
        ", ".join(params),
        f"covers_{decl.decl_id_for_op(op)}({schema_args}) -> bool",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--artifacts-dir", default=os.path.join(REPO, "build", "native_aot")
    )
    parser.add_argument(
        "--allow-stale",
        action="store_true",
        help="generate even when artifact source hashes mismatch the tree",
    )
    args = parser.parse_args()

    from tools.native_aot import export as export_mod

    # Artifact dirs are named by decl_id (one per declaration; family
    # modules under one ops/<dir> produce several). Map them back to
    # their declarations by scanning every aot.py.
    by_id = {}
    for entry in sorted(os.listdir(OPS_DIR)):
        path = os.path.join(OPS_DIR, entry, "aot.py")
        if os.path.exists(path):
            for d in decl.load_declarations(path):
                # Keep the real source path: a family module's decl_ids do
                # not name their own directory (pointwise/aot.py declares
                # acos, add.Tensor, ...), so it cannot be reconstructed.
                by_id[decl.decl_id(d)] = (d, os.path.relpath(path, REPO))

    if not os.path.isdir(args.artifacts_dir):
        # Zero declarations => export wrote nothing and never created
        # the dir. A normal artifacts-free build, not an error (the
        # embedded glob in caffe2/CMakeLists.txt degrades the same way).
        print(f"{args.artifacts_dir}: no artifacts, nothing to generate")
        return

    for entry in sorted(os.listdir(args.artifacts_dir)):
        art_dir = os.path.join(args.artifacts_dir, entry)
        if not os.path.isdir(art_dir):
            continue
        d, decl_path = by_id.get(entry, (None, ""))
        if d is None:
            # Orphaned artifact dir (declaration renamed/removed): its
            # previously generated .cpp would still be globbed by the
            # build and reference a stub that no longer exists -- a link
            # error far from the cause. Remove the generated source and
            # tell the user; the kernel artifacts stay (cheap, inert).
            # Only dirs holding files are op dirs: dirs of dirs are
            # grouping levels (e.g. a per-arch fan-out), not orphans.
            entries = [os.path.join(art_dir, fn) for fn in os.listdir(art_dir)]
            if not any(os.path.isfile(p) for p in entries):
                continue
            removed = []
            for p in entries:
                fn = os.path.basename(p)
                if fn.startswith("aot_") and fn.endswith(".cpp"):
                    os.remove(p)
                    removed.append(fn)
            print(
                f"{entry}: no declaration (renamed or removed?); "
                + (f"deleted stale {', '.join(removed)}" if removed else "skipped")
            )
            continue
        sidecars = []
        stale = []
        for fn in sorted(os.listdir(art_dir)):
            if fn.endswith(".json"):
                with open(os.path.join(art_dir, fn)) as f:
                    sc = json.load(f)
                # Staleness guard: the sidecar records the builder's
                # source closure at export; a mismatch means the kernel
                # source changed since the artifact was compiled.
                if not export_mod.sources_current(sc):
                    stale.append(sc.get("prefix", fn))
                # Generation-time context: toolchains that embed artifact
                # bytes (e.g. raw cubins) read them from the sidecar's dir.
                sc["_dir"] = art_dir
                sidecars.append(sc)
        if stale and not args.allow_stale:
            raise RuntimeError(
                f"{entry}: {len(stale)} artifact(s) were exported from "
                f"different kernel sources than the current tree (e.g. "
                f"{stale[0]}). Re-run tools/native_aot/export.py (stale "
                f"points re-export automatically), or pass --allow-stale."
            )
        if not sidecars:
            continue
        did, key = decl.decl_id(d), d.DISPATCH_KEY
        covers = None
        covers_fn = getattr(d, "cpp_covers", None)
        covers_body = (covers_fn() or "") if covers_fn else ""
        if covers_body:
            params, schema = covers_signature(d.ATEN_OP)
            covers = (params, schema, covers_body)
        src = gen_op(
            did,
            key,
            d,
            sidecars,
            impl_signature_params(d.ATEN_OP),
            covers,
            precomputed_args(d.ATEN_OP),
            decl_path,
        )
        out = os.path.join(art_dir, f"aot_{did}_{key.lower()}.cpp")
        with open(out, "w") as f:
            f.write(src)
        print(f"wrote {out} ({len(sidecars)} kernels)")


if __name__ == "__main__":
    main()
