# Emitted only into files whose kind narrows shapes (see
# Toolchain.NARROWS_SHAPES_TO_INT32); an unused inline function would
# otherwise sit in every generated file's anonymous namespace.
SIZE_GATE_HELPER = """
// This kind's exported ABI carries int32_t shape slots while aten sizes are
// int64_t; the generated gates decline rather than truncate. See
// _int32_size_gate in tools/native_aot/gen_aot_lib.py.
inline bool _naot_dim_too_big(int64_t d) {
  return d > std::numeric_limits<int32_t>::max();
}
"""


# Fast coverage predicate: the declaration's cpp_covers() body over the
# op's FUNCTIONAL schema arguments (plus a trailing optional `out` so
# the .out variant's kwarg binds). Registered as a catch-all custom op;
# torch._native.aot_manifest prefers it over the Python covered_axes
# matching when the library is loaded.
COVERS_FN_TMPL = """
bool {op}_{key_lc}_covers({params}) {{
{body}
  return false;  // undecided above: not covered, the same default the stub takes
}}
"""

COVERS_REG_TMPL = """
TORCH_LIBRARY_FRAGMENT(_native_aot, m) {{
  m.def("{schema}", &::{op}_{key_lc}_covers);
}}
"""


from tools.native_aot import toolchains


def indent(code: str, pad: str) -> str:
    """Re-indent a declaration-supplied C++ block to pad.

    Dedented first: a hook returns a triple-quoted string, so its lines carry the
    indentation of the Python source it was written in, which has nothing to do with
    where it lands in the generated function. Blank edges go for the same reason --
    a block opens right after the brace that introduced it, and callers that want a
    separating line emit one.
    """
    code = textwrap.dedent(code.strip("\n").rstrip())
    return "\n".join(pad + l if l.strip() else l for l in code.splitlines())


def gen_launcher(sidecar: dict) -> str:
    return toolchains.get_toolchain(sidecar["kind"]).gen_launcher(sidecar)


_CURRENT_PROPS = "at::cuda::getCurrentDeviceProperties()"

# Name of the local the generated gates read device properties through. Its
# own prefix, because declaration-supplied bodies share the scope.
_PROPS_LOCAL = "_naot_props"


def _split_params(params: str) -> list[str]:
    """A C++ parameter list split at its TOP-LEVEL commas.

    `params.split(",")` also cuts inside template arguments, and signatures carry
    ones with commas (`std::array<bool, 3>`, `std::pair<at::Tensor, at::Tensor>`).
    Callers then judge fragments, and _int32_size_gate's refusal of unknown
    tensor-shaped types named a type absent from the signature it was given."""
    out: list[str] = []
    depth = 0
    cur = ""
    for ch in params:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out if p.strip()]


def _param_type_and_name(param: str) -> tuple[str, str]:
    """One declaration -> (type without const/ref, parameter name)."""
    name = param.split()[-1].lstrip("&*")
    ctype = param[: -len(name)].strip().removeprefix("const ").rstrip("& ")
    return ctype, name


def _first_tensor_name(params: str) -> str | None:
    """Name of the first plain at::Tensor parameter, or None."""
    for p in _split_params(params):
        ctype, name = _param_type_and_name(p)
        if ctype == "at::Tensor":
            return name
    return None


def _device_match(major: int, minor: int) -> str:
    """The device predicate for one compute capability, read through the local
    _gate_for assigns the properties expression to."""
    return f"{_PROPS_LOCAL}->major == {major} && {_PROPS_LOCAL}->minor == {minor}"


def _spec_from_json(spec):
    """A recorded spec as the DECLARATION stated it: sequences back to tuples.

    The grid distinguishes them -- expand_specs treats a list as an axis and a
    tuple as one compound value -- but JSON has only arrays, so a tuple-valued
    field reached cpp_dispatch as a list and compared silently unequal, emitting
    a cond that never fires. Exact, not a guess: expand_specs consumed every list
    as an axis, so a sequence left in a recorded point was a tuple."""
    if isinstance(spec, list):
        return tuple(_spec_from_json(v) for v in spec)
    if isinstance(spec, dict):
        return {k: _spec_from_json(v) for k, v in spec.items()}
    return spec


def _by_arch(sidecars: list[dict]) -> dict[tuple[int, int], list[dict]]:
    """Group sidecars by the compute capability they were compiled for, in ascending
    order, dropping the loser of the arch-conditional tie-break.

    Grouped rather than one gate over the union, because each device must run kernels
    built for exactly its capability; a union gate would accept a device nothing was
    compiled for. Within one capability both "sm_100a" and "sm_100" run on the
    hardware and the conditional wins, being what the kernels were written against. A
    sidecar with no recorded arch is rejected: there is no hardware to match it to."""
    groups: dict[tuple[int, int], list[dict]] = {}
    conditional: dict[tuple[int, int], bool] = {}
    for sc in sidecars:
        arch = sc.get("arch")
        if not isinstance(arch, str):
            raise RuntimeError(
                f"{sc.get('prefix', '<unnamed>')} in {sc.get('_dir', '?')} "
                f"records no arch. Re-export: the runtime gate is built from "
                f"the arch each artifact was compiled for."
            )
        cc = decl.cc_of(arch)
        is_cond = arch.endswith("a")
        if cc in groups and conditional.get(cc, False) != is_cond:
            # A conditional build for this cc wins outright; a plain one loses.
            if not is_cond:
                continue
            groups[cc] = []
        groups.setdefault(cc, []).append(sc)
        conditional[cc] = conditional.get(cc, False) or is_cond
    return {cc: groups[cc] for cc in sorted(groups)}


# Tensor-shaped C++ types the gate must recognize or refuse: torchgen renders
# Tensor? as at::OptionalTensorRef and Tensor[] as at::ITensorListRef, and
# index.Tensor's covers signature carries c10::List<optional<at::Tensor>> --
# none of which fit the two accessors below.
_TENSOR_ISH = re.compile(r"\bat::\w*Tensor\w*|\bc10::List<")


def _int32_size_gate(params: str) -> str:
    """Runtime gate: decline any call whose tensor has a dimension that
    does not fit in int32.

    aten sizes are int64_t while the exported ABI takes int32 shape slots, so the
    launcher's `static_cast<int32_t>(...)` would truncate a >=2^31 extent into a
    wrong, possibly negative one with no error. Emitted ahead of the prelude and into
    cpp_covers, so no declaration hand-writes it and coverage never claims a shape the
    stub will refuse.

    Bounds the named tensors' dims, not numel(), which would decline a large tensor
    whose collapsed extent is tiny. A prelude that DERIVES an extent must bound that
    value itself, with the emitted `_naot_dim_too_big`; the generator cannot see a
    computed value, so that is a per-declaration review item.

    TODO(native-aot): serving >=2^31 dims needs the exported header's int32 width
    fixed upstream and kernels ported off `t.shape[i]`, which is Int32 whatever the
    symbol; cute.sym_int64() alone is not enough.
    """
    # The at::Tensor names in scope: the prelude sees plain `const at::Tensor&`,
    # cpp_covers sees out-variant outputs as `const std::optional<at::Tensor>&`.
    plain: list[str] = []
    optional: list[str] = []
    for p in _split_params(params):
        ctype, name = _param_type_and_name(p)
        if ctype in ("std::optional<at::Tensor>", "::std::optional<at::Tensor>"):
            optional.append(name)
        elif ctype == "at::Tensor":
            plain.append(name)
        elif _TENSOR_ISH.search(ctype):
            # Each remaining tensor-shaped type needs its own accessor
            # (OptionalTensorRef has no has_value(); the others are
            # sequences), so guessing emits an ungated dim or C++ that does
            # not compile. The next op to use one gets this message.
            raise RuntimeError(
                f"_int32_size_gate: unhandled tensor-like parameter type "
                f"{ctype!r} (arg {name!r}). Teach the gate this type -- gating "
                f"it wrongly would let a >=2^31 dim through the launcher's "
                f"static_cast<int32_t>, or emit C++ that does not compile."
            )
    if not plain and not optional:
        return ""
    checks = [
        f"{n}.sizes().end() != std::find_if({n}.sizes().begin(), {n}.sizes().end(), _naot_dim_too_big)"
        for n in plain
    ]
    checks += [
        f"({n}.has_value() && {n}->sizes().end() != "
        f"std::find_if({n}->sizes().begin(), {n}->sizes().end(), _naot_dim_too_big))"
        for n in optional
    ]
    return (
        "  // Size gate: the DSL's exported ABI carries int32_t shape slots\n"
        "  // (see _int32_size_gate); a bigger dim would truncate silently.\n"
        f"  if (C10_UNLIKELY({' || '.join(checks)})) return false;\n"
    )


def gen_op(
    op: str,
    key: str,
    d,
    sidecars: list[dict],
    impl_params: str,
    covers: tuple[str, str, str] | None = None,
    precomputed: list[str] | None = None,
    decl_path: str = "",
) -> str:
    def _branch(s: dict, pad: str) -> str:
        spec = _spec_from_json(s["spec"])
        dispatch = d.cpp_dispatch(spec).strip()
        launch = d.cpp_launch(spec, f"launch_{s['prefix']}")
        return (
            f"{pad}if ({dispatch}) {{\n{indent(launch, pad + '  ')}\n"
            f"{pad}  return true;\n{pad}}}"
        )

    # One cond chain per compute capability (see _by_arch).
    groups = _by_arch(sidecars)
    # Shipping an arch the declaration disowns is a packaging bug: error rather
    # than gate on kernels the op does not claim to support. Over EVERY exported
    # tree, ahead of the tie-break below: a disowned tree of the same capability as
    # a claimed one loses that tie-break, and would pass unnoticed.
    if unclaimed := {sc["arch"] for sc in sidecars} - set(decl.archs_of(d)):
        # Name the directories and say DELETE: export skips arches outside ARCHS,
        # so it never prunes these trees and every later build fails identically.
        # .get because gen_op is also called directly, with no generation-time _dir.
        trees = sorted(
            {sc.get("_dir", "?") for sc in sidecars if sc["arch"] in unclaimed}
        )
        raise RuntimeError(
            f"{op}: artifacts exported for {sorted(unclaimed)} but the "
            f"declaration supports only {decl.archs_of(d)}. Delete "
            f"{', '.join(trees) or 'those arch trees'} -- export.py skips "
            f"unsupported arches, so it will not remove them -- then re-export. "
            f"A bare re-export will NOT clear this; only deleting the tree does. "
            f"(A backstop: export resolves an on-device arch to the spelling the "
            f"declaration claims, so reaching this means the tree predates that or "
            f"ARCHS was narrowed since.)"
        )

    # From the sidecars that SURVIVED the tie-break: a launcher for a dropped
    # candidate is defined and never called, which is -Wunused-function in an
    # anonymous namespace and fatal under CI's WERROR.
    sidecars = [sc for scs in groups.values() for sc in scs]

    def _gate_for(props: str) -> str:
        accept = " || ".join(f"({_device_match(*cc)})" for cc in groups)
        return (
            f"  // Device gate: one branch per shipped capability "
            f"({', '.join(f'{maj}.{min_}' for maj, min_ in groups)})\n"
            f"  // Read once into a local: this gate and every branch below ask\n"
            f"  // the same question, and the accessor is a call per read.\n"
            f"  const auto* {_PROPS_LOCAL} = {props};\n"
            f"  if (!({accept})) return false;\n"
        )

    arch_gate = _gate_for(_CURRENT_PROPS)
    branches = [
        f"  if ({_device_match(*cc)}) {{\n"
        + "\n".join(_branch(s, "    ") for s in scs)
        + "\n  }"
        for cc, scs in groups.items()
    ]
    # Defaulted to a callable so the use sites need no condition. `or (lambda)`
    # rather than a getattr default: the contract's other spelling of "no hook" is
    # the attribute set to None, which a default does not cover. The `or ""` below
    # stays too -- a hook the declaration DID export may still return None.
    prelude_fn = getattr(d, "cpp_dispatch_prelude", None) or (lambda: "")
    helpers_fn = getattr(d, "cpp_helpers", None) or (lambda: "")
    prelude = prelude_fn() or ""
    # Dedented for the same reason as indent(): these are file-scope definitions.
    helpers = textwrap.dedent((helpers_fn() or "").rstrip())
    # Only kinds whose exported ABI takes i32 extents need the size gate. ANY
    # narrowing kind among this op's points is enough: any point may be selected.
    narrows = any(
        toolchains.get_toolchain(sc["kind"]).NARROWS_SHAPES_TO_INT32 for sc in sidecars
    )
    covers_fn = covers_reg = ""
    if covers is not None:
        covers_params, covers_schema, covers_body = covers
        # Coverage must be no wider than the stub's acceptance, or gated calls
        # lose their JIT route -- hence the same arch gate here. It reads the
        # TENSOR's device, not the current one: covers runs before any device
        # guard, so on a mixed-capability host they can differ.
        _cov_t = _first_tensor_name(covers_params)
        if _cov_t is None:
            # Refused rather than falling back to the current device: with no
            # tensor to ask is_cuda() of, the predicate would initialize a CUDA
            # context on every call and abort on a GPU-less host, where the
            # answer is simply false.
            raise RuntimeError(
                f"{op}: cpp_covers needs a plain at::Tensor parameter to read the "
                f"device from, and this signature has none ({covers_params}). "
                f"Drop cpp_covers for this op -- the Python covered_axes path "
                f"still applies -- or route it through an op whose schema takes a "
                f"Tensor."
            )
        covers_props = f"at::cuda::getDeviceProperties({_cov_t}.device().index())"
        # is_cuda BEFORE reading properties: covers is a catch-all custom op, so a
        # CPU tensor reaches it, and getDeviceProperties(-1) falls back to the
        # current device -- initializing a CUDA context from a predicate the router
        # runs on every call, and aborting on a GPU-less host.
        cuda_first = f"  if (!{_cov_t}.is_cuda()) return false;\n"
        covers_fn = COVERS_FN_TMPL.format(
            op=op,
            key_lc=key.lower(),
            params=covers_params,
            body=cuda_first
            + _gate_for(covers_props)
            + (_int32_size_gate(covers_params) if narrows else "")
            + indent(covers_body, "  "),
        )
        # Escaped: the schema goes into a C++ string literal, and a
        # double-quoted default in native_functions.yaml (str mode="constant")
        # closed it early -- a compile error inside a @generated file.
        covers_reg = COVERS_REG_TMPL.format(
            op=op,
            key_lc=key.lower(),
            schema=covers_schema.replace("\\", "\\\\").replace('"', '\\"'),
        )
    # State the precompute behaviour where authors debug: a raw dim compared
    # unwrapped against self.dim()-1 silently declines every negative-dim call.
    if precomputed:
        note = (
            f"Structured META precomputes (impl receives them wrapped/"
            f"replaced): {', '.join(precomputed)}"
        )
    else:
        note = (
            "Structured META precomputes NOTHING for this op: schema "
            "args (incl. any dim) arrive RAW -- wrap dims before comparing."
        )
    return FILE_TMPL.format(
        op=op,
        key_lc=key.lower(),
        key_uc=key.upper(),
        decl_path=decl_path or f"the declaration for aten::{op}",
        precompute_note=note,
        covers_fn=covers_fn,
        covers_reg=covers_reg,
        covers_include=(
            "#include <torch/library.h>\n\n" if covers is not None else "\n"
        ),
        kernel_includes="\n".join(
            dict.fromkeys(  # ordered dedup across sidecars
                line
                for sc in sidecars
                for tc in [toolchains.get_toolchain(sc["kind"])]
                for line in (*tc.kernel_includes(sc), *tc.launcher_includes)
            )
        ),
        launchers="\n".join(
            ([helpers] if helpers else []) + [gen_launcher(s) for s in sidecars]
        ),
        params=impl_params,
        size_gate_helper=SIZE_GATE_HELPER if narrows else "",
        cond=arch_gate
        + (_int32_size_gate(impl_params) if narrows else "")
        + ("\n" + indent(prelude, "  ") if prelude.strip() else ""),
        guards="\n".join(branches),
    )


def _structured_group(op: str):
    from torchgen.gen import get_grouped_native_functions, parse_native_yaml
    from torchgen.model import NativeFunctionsGroup

    aten = os.path.join(REPO, "aten", "src", "ATen")
    parsed = parse_native_yaml(
        os.path.join(aten, "native", "native_functions.yaml"),
        os.path.join(aten, "native", "tags.yaml"),
    )
    for g in get_grouped_native_functions(parsed.native_functions):
        # Base names repeat across groups (bmm vs bmm.dtype), so the signature
        # must come from the STRUCTURED one; a qualified op matches exactly.
        if isinstance(g, NativeFunctionsGroup) and g.structured:
            fname = g.functional.func.name
            if (str(fname) if "." in op else fname.name.base) == op:
                return g
    raise RuntimeError(f"no structured group for {op}")


def impl_signature_params(op: str) -> str:
    from torchgen.api import structured
    from torchgen.context import native_function_manager

    g = _structured_group(op)
    with native_function_manager(g):
        return ", ".join(b.decl() for b in structured.impl_arguments(g))


def precomputed_args(op: str) -> list[str]:
    """Schema argument names the structured META precomputes before the impl runs
    -- index_add's dim arrives maybe_wrap_dim'ed, sum.dim_IntList's arrives RAW.
    Declarations must know which they get, so the generated .cpp states it per
    op."""
    g = _structured_group(op)
    pre = g.out.precomputed
    return sorted(pre.replace.keys()) if pre is not None else []


def covers_signature(op: str) -> tuple[str, str]:
    """(C++ params, torch.library schema) for the fast coverage
    predicate: the FUNCTIONAL schema arguments (SymInt degraded to int
    -- symbolic sizes can't be covered anyway; a failed bind falls back
    to the Python path) plus the out variant's outputs as trailing
    optionals so calls arriving through the .out overload bind too.
    """
    from torchgen.api.types import DispatcherSignature
    from torchgen.context import native_function_manager

    g = _structured_group(op)
    with native_function_manager(g):
        sig = DispatcherSignature.from_schema(g.functional.func, symint=False)
        params = [a.decl() for a in sig.arguments()]
    # Render per-argument from the model (not string surgery on the
    # whole schema): SymInt -> int argument-by-argument, and the
    # kwarg-only marker reconstructed from the model's split.
    args = g.functional.func.arguments
    pos = [str(a).replace("SymInt", "int") for a in args.flat_positional]
    kw = [str(a).replace("SymInt", "int") for a in args.flat_kwarg_only]
    pieces = pos + (["*", *kw] if kw else [])
    # Trailing out-variant outputs bind the .out overload's kwargs;
    # appended last, so kwarg-only exactly when the schema already has
    # a kwarg section (matching the C++ params' positional binding).
    for a in g.out.func.arguments.out:
        params.append(f"const std::optional<at::Tensor>& {a.name}")
        pieces.append(f"Tensor? {a.name}=None")
    schema_args = ", ".join(pieces)
    # Op name in the registered schema is the decl_id (dots are illegal
    # in custom-op names); the runtime resolves covers_<decl_id> too.
    return (
        ", ".join(params),
        f"covers_{decl.decl_id_for_op(op)}({schema_args}) -> bool",
    )
