from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path


# Every c-shim header a generated AOTInductor model can reference. The rename
# list must be a superset of these, so any header that declares aoti_torch_*
# symbols has to be listed here.
SHIM_HEADERS = [
    "torch/csrc/inductor/aoti_torch/c/shim.h",
    "torch/csrc/inductor/aoti_torch/c/shim_cpu.h",
    "torch/csrc/inductor/aoti_torch/c/shim_mps.h",
    "torch/csrc/inductor/aoti_torch/c/shim_xpu.h",
    "torch/csrc/inductor/aoti_torch/c/shim_deprecated.h",
    "torch/csrc/inductor/aoti_torch/generated/c_shim_cpu.h",
    "torch/csrc/inductor/aoti_torch/generated/c_shim_cuda.h",
    "torch/csrc/inductor/aoti_torch/generated/c_shim_mps.h",
    "torch/csrc/inductor/aoti_torch/generated/c_shim_xpu.h",
    "torch/csrc/inductor/aoti_torch/generated/c_shim_aten.h",
]

HEADER_REL_PATH = "torch/csrc/inductor/aoti_torch/c/shim_symbol_prefix.h"

# A name immediately followed by "(" is a declaration or call, not a stray
# mention in prose.
_SYMBOL_RE = re.compile(r"\b(aoti_torch_[A-Za-z0-9_]+)\s*\(")

# clang-format column limit; longer #define lines wrap onto a continuation.
_MAX_LINE = 80

# Split so this generator's own source does not contain the literal @generated
# marker, which would make tooling treat the generator itself as generated.
_GENERATED_TAG = "// @" + (
    "generated by torchgen/gen_aoti_shim_symbol_prefix.py. Do not edit by hand."
)

_DOC_COMMENT = """\
// Optional private-namespace layer for the aoti_torch_* C-ABI shims. A
// generated AOTInductor model normally imports the extern "C" aoti_torch_*
// symbols and binds them, at load, to whatever provides them -- normally
// libtorch (over at::Tensor). A backend that ships its OWN shim implementations
// over a different tensor type (e.g. ExecuTorch's SlimTensor) cannot coexist
// with libtorch in one process: both export the identical aoti_torch_* names,
// so the model binds by ELF load order and a SlimTensor* can be read as an
// at::Tensor* -> crash. When the model AND that backend's shim library are both
// compiled with -DAOTI_SHIM_SYMBOL_PREFIX=<prefix> this header renames every
// referenced aoti_torch_* token to <prefix>aoti_torch_*, giving the backend a
// private, disjoint shim ABI while libtorch keeps the unprefixed names. With
// the define unset (the default), this header expands to nothing and not a
// single token changes. The list below is the set of aoti_torch_* shims a
// generated model may import that must be given the private prefix. When the
// prefix is set, each listed token is renamed to <prefix>aoti_torch_* on the
// model's import side (and, for the shims the backend actually implements, on
// the backend's export side too), so the model binds to the backend's shim
// (e.g. ExecuTorch's SlimTensor shims) and never to libtorch. This list must be
// a SUPERSET of the shims the backend implements. A listed token the backend
// does NOT implement is still renamed, so the model's reference becomes an
// unresolved <prefix>aoti_torch_* symbol -- a loud link or load error --
// instead of silently binding to libtorch's at::Tensor shim and reading the
// backend's tensor handle as an at::Tensor* (a latent crash / memory
// corruption). Omitting an imported token has one of two failure modes. For a
// raw-literal or runtime-header call site the reference stays the unprefixed
// aoti_torch_* name and silently binds to libtorch's at::Tensor shim -- the
// latent crash above. For a name routed through get_c_shim_func_name the Python
// codegen prefixed the call already, so a missing #define here leaves the call
// prefixed but the declaration unprefixed -- a loud undeclared-symbol / link
// error. To rule out both, this list is generated as a complete superset of
// every aoti_torch_* declared across the c-shim headers, so no imported token
// can be missed."""

_MACRO_BLOCK = """\
#define AOTI_SHIM_CONCAT2_(a, b) a##b
#define AOTI_SHIM_CONCAT_(a, b) AOTI_SHIM_CONCAT2_(a, b)
#define AOTI_SHIM_RENAME_(name) AOTI_SHIM_CONCAT_(AOTI_SHIM_SYMBOL_PREFIX, name)"""


def caffe2_root() -> Path:
    # torchgen/ sits directly under caffe2/, and the shim headers live under
    # caffe2/torch/..., so caffe2/ is this file's grandparent.
    return Path(__file__).resolve().parent.parent


def collect_symbols(root: Path) -> list[str]:
    symbols: set[str] = set()
    for rel in SHIM_HEADERS:
        path = root / rel
        if not path.exists():
            # A missing header silently drops its symbols from the rename list,
            # which reintroduces the exact silent-bind hazard this generator
            # prevents. Warn loudly so an incomplete run is noticed.
            sys.stderr.write(f"warning: shim header not found, skipping: {rel}\n")
            continue
        symbols.update(_SYMBOL_RE.findall(path.read_text()))
    return sorted(symbols)


def _render_define(sym: str) -> str:
    line = f"#define {sym} AOTI_SHIM_RENAME_({sym})"
    if len(line) <= _MAX_LINE:
        return line
    return f"#define {sym} \\\n  AOTI_SHIM_RENAME_({sym})"


def generate_header(root: Path) -> str:
    defines = "\n".join(_render_define(sym) for sym in collect_symbols(root))
    return f"""\
{_GENERATED_TAG}
{_DOC_COMMENT}

#ifndef AOTI_TORCH_SHIM_SYMBOL_PREFIX_H
#define AOTI_TORCH_SHIM_SYMBOL_PREFIX_H

#ifdef AOTI_SHIM_SYMBOL_PREFIX
{_MACRO_BLOCK}

{defines}
#endif // AOTI_SHIM_SYMBOL_PREFIX

#endif // AOTI_TORCH_SHIM_SYMBOL_PREFIX_H
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--output", help="write the generated header to this path")
    group.add_argument(
        "--check",
        help="regenerate in memory and fail with a diff if this path is stale",
    )
    args = parser.parse_args()

    content = generate_header(caffe2_root())

    if args.output:
        Path(args.output).write_text(content)
        return

    existing = Path(args.check).read_text()
    if existing == content:
        return
    diff = "\n".join(
        difflib.unified_diff(
            existing.splitlines(),
            content.splitlines(),
            fromfile=f"{args.check} (stale)",
            tofile="regenerated",
            lineterm="",
        )
    )
    sys.stderr.write(
        f"{args.check} is out of date. Regenerate with "
        f"`python torchgen/gen_aoti_shim_symbol_prefix.py --output {args.check}`.\n"
        f"{diff}\n"
    )
    sys.exit(1)


if __name__ == "__main__":
    main()
