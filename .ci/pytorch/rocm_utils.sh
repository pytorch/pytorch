#!/bin/bash
# ROCm-specific utility functions shared across CI scripts

ROCM_UTILS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Build rocm-composable-kernel (ck4inductor) wheel
# Usage: build_rocm_ck_wheel <output_dir>
build_rocm_ck_wheel() {
  local raw_output_dir="${1:?build_rocm_ck_wheel: output directory required}"
  mkdir -p "$raw_output_dir"
  local output_dir
  output_dir="$(cd "$raw_output_dir" && pwd)"
  if [[ -z "$output_dir" ]]; then
    echo "build_rocm_ck_wheel: failed to resolve output directory '$raw_output_dir'" >&2
    return 1
  fi

  echo "Building rocm-composable-kernel (ck4inductor) wheel at $(date)"

  local pin_file="${ROCM_UTILS_DIR}/../docker/ci_commit_pins/rocm-composable-kernel.txt"
  if [[ ! -f "$pin_file" ]]; then
    echo "build_rocm_ck_wheel: pin file not found at $pin_file" >&2
    return 1
  fi
  local ck_commit
  ck_commit=$(tr -d '[:space:]' < "$pin_file")
  echo "CK commit: $ck_commit"

  # Use a fresh tmp dir keyed by commit prefix; remove any stale state from prior runs
  # so `git init` / `git fetch` start clean.
  local ck_dir="/tmp/ck-${ck_commit:0:12}"
  rm -rf "$ck_dir"

  # Cleanup runs on every exit path from this function (success, return, or set -e abort
  # via the caller's ERR/EXIT), via the explicit rm at the end and via the trap below.
  # `trap RETURN` alone is unreliable under `set -e` because the shell may exit before
  # the function returns, so we also rm at the end of the success path. Expand $ck_dir
  # at trap-set time (rather than trap-fire time) since it is a local that may go out
  # of scope, and its value never changes within this function.
  # shellcheck disable=SC2064
  trap "rm -rf '$ck_dir'" RETURN

  git init "$ck_dir"
  pushd "$ck_dir" >/dev/null || return 1
  git fetch --depth 1 https://github.com/ROCm/composable_kernel.git "$ck_commit"
  git checkout FETCH_HEAD

  # ck/config.h is generated by CK's build rather than checked in, so it is in
  # neither the wheel nor $ROCM_HOME now that ROCm has stopped installing the CK
  # headers system-wide. Every CK choice then fails to compile and is silently
  # discarded. Generate it here and package it with the rest of include/ck.
  #
  # CK's own CMake cannot produce it in CI container: CMakeLists.txt calls
  # find_package(ROCM), find_package(hip REQUIRED) and enable_language(HIP), and
  # the wheel-build image has hipcc but no ROCm CMake packages. config.h.in only
  # substitutes plain variables, so the helper sets them and runs the same
  # configure_file in cmake script mode.
  #
  # One header serves three targets: gfx942,gfx950,gfx1250. Arch-specific macros
  # are unioned.
  #
  # Referenced via ROCM_UTILS_DIR, not a relative path: callers run from the
  # pytorch root and this function has already pushd'd into $ck_dir.
  local ck_config_generator="${ROCM_UTILS_DIR}/generate_ck_config_h.cmake"
  if [[ ! -f "$ck_config_generator" ]]; then
    echo "build_rocm_ck_wheel: generator not found at $ck_config_generator" >&2
    popd >/dev/null || true
    return 1
  fi
  echo "Generating include/ck/config.h for gfx942;gfx950;gfx1250"
  if ! cmake \
      -D "CK_SOURCE_DIR=${ck_dir}" \
      -D "CK_OUTPUT=${ck_dir}/include/ck/config.h" \
      -D "CK_GPU_TARGETS=gfx942;gfx950;gfx1250" \
      -P "$ck_config_generator"; then
    echo "build_rocm_ck_wheel: failed to generate ck/config.h" >&2
    popd >/dev/null || true
    return 1
  fi

  # The include package-data globs match *.hpp and *.inc, so the .h just
  # generated would not be picked up. Add it explicitly. Bail out rather than
  # ship a wheel that is silently missing the header.
  local ck_include_unpatched='"ck4inductor.include" = ["ck/**/*.hpp", "ck_tile/**/*.hpp", "ck_tile/**/*.inc"]'
  local ck_include_patched='"ck4inductor.include" = ["ck/**/*.hpp", "ck/config.h", "ck_tile/**/*.hpp", "ck_tile/**/*.inc"]'
  if grep -qxF "$ck_include_unpatched" pyproject.toml; then
    echo "Patching pyproject.toml to package ck/config.h"
    if ! python -c 'import sys; s = open("pyproject.toml").read(); open("pyproject.toml", "w").write(s.replace(sys.argv[1], sys.argv[2], 1))' "$ck_include_unpatched" "$ck_include_patched"; then
      echo "build_rocm_ck_wheel: failed to patch pyproject.toml" >&2
      popd >/dev/null || true
      return 1
    fi
  elif ! grep -qF '"ck/config.h"' pyproject.toml; then
    echo "build_rocm_ck_wheel: unrecognized ck4inductor.include package-data in pyproject.toml" >&2
    popd >/dev/null || true
    return 1
  fi

  python -m build --wheel --no-isolation --outdir "$output_dir"
  popd >/dev/null || return 1

  # Verify the wheel actually landed so downstream copies don't silently skip it.
  if ! compgen -G "$output_dir/rocm_composable_kernel*.whl" >/dev/null; then
    echo "build_rocm_ck_wheel: no rocm_composable_kernel wheel produced in $output_dir" >&2
    return 1
  fi

  rm -rf "$ck_dir"
  echo "Finished building rocm-composable-kernel (ck4inductor) wheel at $(date)"
}
